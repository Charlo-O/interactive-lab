function wobble(points, amount, seed) {
  const out = [];
  points.forEach(([x, y], i) => {
    const [nx, ny] = points[(i + 1) % points.length];
    const length = Math.hypot(nx - x, ny - y);
    const steps = Math.max(1, Math.round(length / 18));
    for (let s = 0; s < steps; s++) {
      const t = s / steps;
      const phase = seed + i * 1.7 + s * 2.3;
      const w = s === 0 ? 0 : amount;
      out.push([
        x + (nx - x) * t + w * Math.sin(phase * 2.1) * 0.8,
        y + (ny - y) * t + w * Math.sin(phase * 3.3 + 1.2) * 0.8
      ]);
    }
  });
  return out;
}

// Corner cutting keeps the shape but rounds it the way a brush does.
function chaikin(points, iterations) {
  let current = points;
  for (let it = 0; it < iterations; it++) {
    const next = [];
    current.forEach(([x, y], i) => {
      const [nx, ny] = current[(i + 1) % current.length];
      next.push([x * 0.75 + nx * 0.25, y * 0.75 + ny * 0.25], [x * 0.25 + nx * 0.75, y * 0.25 + ny * 0.75]);
    });
    current = next;
  }
  return current;
}

function fillShape(g, color, points, { alpha = 1, rough = 1.1, seed = 1, smooth = 2 } = {}) {
  const base = rough > 0 ? wobble(points, rough, seed) : points;
  const ring = rough > 0 ? chaikin(base, smooth) : base;
  g.globalAlpha = alpha;
  g.fillStyle = color;
  g.beginPath();
  ring.forEach(([x, y], i) => (i ? g.lineTo(x, y) : g.moveTo(x, y)));
  g.closePath();
  g.fill();
  g.globalAlpha = 1;
}

const rad = degrees => degrees * Math.PI / 180;
const onEllipse = (cx, cy, a, b, degrees) => [cx + a * Math.cos(rad(degrees)), cy + b * Math.sin(rad(degrees))];

// A band between two ellipse arcs; angles are measured clockwise from +x in
// image space, so 90 degrees is the front (bottom) of the ellipse.
function arcBand(g, color, cx, cy, inner, outer, from, to, { alpha = 1, taper = 0 } = {}) {
  const n = 96;
  const top = [];
  const bottom = [];
  for (let i = 0; i <= n; i++) {
    const t = i / n;
    const angle = from + (to - from) * t;
    const pinch = taper ? Math.pow(Math.sin(Math.PI * t), taper) : 1;
    const [a0, b0] = inner;
    const [a1, b1] = outer;
    const a = a0 + (a1 - a0) * pinch;
    const b = b0 + (b1 - b0) * pinch;
    top.push(onEllipse(cx, cy, a0, b0, angle));
    bottom.push(onEllipse(cx, cy, a, b, angle));
  }
  fillShape(g, color, [...top, ...bottom.reverse()], { alpha, rough: 0 });
}

